def build_presentation(out_path, notes_path):
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    total = len(SLIDES)
    for i, spec in enumerate(SLIDES, start=1):
        slide = BUILDERS[spec["layout"]](prs, spec, i, total)
        slide.notes_slide.notes_text_frame.text = spec["speech"]
    prs.save(out_path)
    write_notes_md(notes_path, SLIDES)
    tm = sum(minutes(s["time"]) for s in SLIDES)
    print(f"Готово: {out_path} ({total} слайдов, ~{tm:.1f} мин), {notes_path}")
    if WARNINGS:
        print(f"Предупреждений: {len(WARNINGS)} (см. stderr)")


def main():
    ap = argparse.ArgumentParser(description="Генератор презентации по палеогеномике неандертальцев")
    ap.add_argument("--out", default=str(BASE / "Neanderthal_Paleogenomics.pptx"))
    ap.add_argument("--notes", default=str(BASE / "SPEAKER_NOTES.md"))
    args = ap.parse_args()
    build_presentation(args.out, args.notes)


if __name__ == "__main__":
    main()
