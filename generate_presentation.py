def build_table(prs, spec, n, total):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    set_bg(slide, C["bg"])
    add_title_bar(slide, spec["title"], n)
    header, rows = spec["table_header"], spec["table_rows"]
    l, t, w = MARGIN_X, BODY_TOP + 0.05, SW - 2 * MARGIN_X
    col_w = [1.2, 3.9, 3.7, 3.33]
    h = BODY_BOTTOM - t
    shape = slide.shapes.add_table(len(rows) + 1, len(header), Inches(l), Inches(t), Inches(w), Inches(h))
    tbl = shape.table
    for j, cw_ in enumerate(col_w):
        tbl.columns[j].width = Inches(cw_)
    tbl.rows[0].height = Inches(0.5)
    for i in range(1, len(rows) + 1):
        tbl.rows[i].height = Inches((h - 0.5) / len(rows))

    def fill_cell(cell, text, size, bold, color, bg):
        cell.fill.solid()
        cell.fill.fore_color.rgb = rgb(bg)
        cell.margin_left = cell.margin_right = Inches(0.08)
        cell.margin_top = cell.margin_bottom = Inches(0.04)
        cell.vertical_anchor = MSO_ANCHOR.MIDDLE
        tf = cell.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
        for r_ in list(p.runs):
            r_._r.getparent().remove(r_._r)
        run = p.add_run()
        run.text = text
        style_run(run, size, bold, color)

    for j, htxt in enumerate(header):
        fill_cell(tbl.cell(0, j), htxt, 16, True, "FFFFFF", C["navy"])
    for i, row in enumerate(rows, start=1):
        bg = "FFFFFF" if i % 2 else C["soft"]
        for j, val in enumerate(row):
            fill_cell(tbl.cell(i, j), val, 14, j == 0, C["amber"] if j == 0 else C["ink"], bg)
            if j == 0:
                tbl.cell(i, j).text_frame.paragraphs[0].runs[0].font.color.rgb = rgb(C["navy"])
    add_footer(slide, spec["cites"], n, total)
    return slide


def build_content(prs, spec, n, total):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    set_bg(slide, C["bg"])
    add_title_bar(slide, spec["title"], n)
    has_img = bool(spec["images"])
    left_w = 5.35 if has_img else SW - 2 * MARGIN_X
    stats = spec["stats"]
    stats_h = 1.15 if stats else 0
    bullets_h = (BODY_BOTTOM - BODY_TOP) - (stats_h + 0.2 if stats else 0)
    add_bullets(slide, MARGIN_X, BODY_TOP, left_w, bullets_h, spec["bullets"], max_pt=19)
    if stats:
        add_stats(slide, MARGIN_X, BODY_BOTTOM - stats_h, left_w, stats_h, stats)
    if has_img:
        img_l = MARGIN_X + left_w + 0.3
        place_images(slide, spec["images"], img_l, BODY_TOP, SW - MARGIN_X - img_l, BODY_BOTTOM - BODY_TOP)
    add_footer(slide, spec["cites"], n, total)
    return slide


def build_sources(prs, spec, n, total):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    set_bg(slide, C["bg"])
    add_title_bar(slide, spec["title"] + " — спасибо за внимание!", n)
    refs = [f"[{c}] {REF[c]}" for c in spec["cites"]]
    mid = math.ceil(len(refs) / 2)
    colw = (SW - 2 * MARGIN_X - 0.3) / 2
    for k, part in enumerate((refs[:mid], refs[mid:])):
        sz = fit_size(part, colw - 0.1, BODY_BOTTOM - BODY_TOP, max_pt=13, min_pt=9, space_after_pt=5)
        tb = slide.shapes.add_textbox(Inches(MARGIN_X + k * (colw + 0.3)), Inches(BODY_TOP), Inches(colw),
                                      Inches(BODY_BOTTOM - BODY_TOP))
        tf = tb.text_frame
        tf.word_wrap = True
        for i, txt in enumerate(part):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.space_after = Pt(5)
            r = p.add_run()
            r.text = txt
            style_run(r, sz, False, C["ink"])
    add_footer(slide, [], n, total)
    return slide


BUILDERS = {"title": build_title, "cards": build_cards, "table": build_table,
            "content": build_content, "sources": build_sources}


