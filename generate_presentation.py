def resolve_image(paper, suffix):
    """Ищет markdown/images/<paper>_*/*<suffix>.png; возвращает путь или None."""
    if not IMG_ROOT.exists():
        return None
    hits = sorted(glob.glob(str(IMG_ROOT / f"{paper}_*" / f"*{suffix}.png")))
    return hits[0] if hits else None


def fit_box(img_w, img_h, bl, bt, bw, bh):
    scale = min(bw / img_w, bh / img_h)
    w, h = img_w * scale, img_h * scale
    return bl + (bw - w) / 2, bt + (bh - h) / 2, w, h, scale


def image_size_px(path):
    w, h = PptxImage.from_file(path).size
    return w, h


def place_image(slide, spec, l, t, w, h):
    """Картинка + рамка + подпись в пределах бокса (l,t,w,h). Не падает при отсутствии файла."""
    paper, suffix, caption = spec
    cap_h = 0.3
    ph = h - cap_h
    add_rect(slide, l, t, w, ph, fill="FFFFFF", line=C["line"])
    path = resolve_image(paper, suffix)
    if path is None:
        warn(f"Изображение не найдено: paper={paper}, suffix={suffix}")
        add_text(slide, l + 0.1, t + ph / 2 - 0.4, w - 0.2, 0.8,
                 f"[Рисунок недоступен]\n{caption}", size=12, italic=True,
                 color=C["muted"], align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
    else:
        try:
            iw, ih = image_size_px(path)
            pad = 0.1
            x, y, pw, phh, _ = fit_box(iw, ih, l + pad, t + pad, w - 2 * pad, ph - 2 * pad)
            slide.shapes.add_picture(path, Inches(x), Inches(y), Inches(pw), Inches(phh))
        except Exception as exc:  # noqa: BLE001
            warn(f"Не удалось вставить {path}: {exc}")
            add_text(slide, l + 0.1, t + ph / 2 - 0.4, w - 0.2, 0.8, f"[Ошибка изображения]\n{caption}",
                     size=12, italic=True, color=C["muted"], align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
    add_text(slide, l, t + ph + 0.02, w, cap_h - 0.02, caption, size=10, italic=True,
             color=C["muted"], align=PP_ALIGN.CENTER)


def place_images(slide, specs, l, t, w, h):
    if not specs:
        return
    if len(specs) == 1:
        place_image(slide, specs[0], l, t, w, h)
        return
    # два изображения: выбираем вертикальную или горизонтальную раскладку по площади
    gap = 0.15
    sizes = []
    for s in specs:
        p = resolve_image(s[0], s[1])
        try:
            sizes.append(image_size_px(p) if p else (4, 3))
        except Exception:  # noqa: BLE001
            sizes.append((4, 3))

    def total_area(horizontal):
        area = 0
        for (iw, ih) in sizes:
            if horizontal:
                bw, bh = (w - gap) / 2, h - 0.3
            else:
                bw, bh = w, (h - gap) / 2 - 0.3
            _, _, pw, ph_, _ = fit_box(iw, ih, 0, 0, bw, bh)
            area += pw * ph_
        return area

    if total_area(True) >= total_area(False):
        bw = (w - gap) / 2
        place_image(slide, specs[0], l, t, bw, h)
        place_image(slide, specs[1], l + bw + gap, t, bw, h)
    else:
        bh = (h - gap) / 2
        place_image(slide, specs[0], l, t, w, bh)
        place_image(slide, specs[1], l, t + bh + gap, w, bh)


