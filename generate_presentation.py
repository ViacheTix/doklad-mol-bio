def minutes(s):
    try:
        return float(s.split()[0].replace(",", "."))
    except Exception:  # noqa: BLE001
        return 0.0


def write_notes_md(path, slides):
    total = sum(minutes(s["time"]) for s in slides)
    lines = [
        "# SPEAKER_NOTES.md — досье докладчика",
        "",
        "**Тема:** Генетика неандертальцев: эволюция методов палеогеномики",
        f"**Слайдов:** {len(slides)}  ·  **Расчётное время:** ~{total:.1f} мин  ·  **Язык:** русский",
        "",
        "> Файл сгенерирован скриптом `generate_presentation.py` из тех же данных, что и слайды и заметки в .pptx. "
        "Все цифры взяты из `digests/*.md` и `markdown/*.md`. Если нужно сократить доклад до ~20 минут, пропустите слайды 20 и 22.",
        "",
        "---",
        "",
    ]
    for i, s in enumerate(slides, start=1):
        lines += [f"## Слайд {i}. {s['title']}", ""]
        lines += ["**Ключевые статьи (авторы, год, журнал):**"]
        for c in s["cites"]:
            lines.append(f"- [{c}] {REF[c]}")
        lines += ["", f"**Визуальная раскладка слайда:** {s['visual']}", "", f"**Расчётное время:** {s['time']}", ""]
        if s.get("images"):
            lines.append("**Рисунки на слайде:** " + "; ".join(f"{im[2]} (`markdown/images/{im[0]}_*/…{im[1]}.png`)" for im in s["images"]))
            lines.append("")
        lines += ["### Текст речи докладчика", "", s["speech"], "", "### Как читать графики на слайде", "", s["graph"], "",
                  "### Возможные вопросы комиссии и ответы", ""]
        for q, a in s["qa"]:
            lines += [f"- **Вопрос:** {q}", f"  **Ответ:** {a}"]
        lines += ["", "---", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8")


