WARNINGS = []


def warn(msg):
    WARNINGS.append(msg)
    print(f"[WARN] {msg}", file=sys.stderr)


def est_height(paras, size_pt, width_in, space_after_pt=7, factor=0.52):
    """Грубая оценка высоты текста в дюймах (кириллица Calibri)."""
    cpl = max(10, int(width_in * 72 / (size_pt * factor)))
    lines = sum(max(1, math.ceil(len(p) / cpl)) for p in paras)
    return lines * size_pt * 1.22 / 72 + len(paras) * space_after_pt / 72


def fit_size(paras, width_in, height_in, max_pt=20, min_pt=11, **kw):
    size = max_pt
    while size > min_pt and est_height(paras, size, width_in, **kw) > height_in:
        size -= 1
    return size


def set_bg(slide, color):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = rgb(color)


def add_rect(slide, l, t, w, h, fill=None, line=None, shape=MSO_SHAPE.RECTANGLE, line_w=0.75, radius=None):
    shp = slide.shapes.add_shape(shape, Inches(l), Inches(t), Inches(w), Inches(h))
    if fill:
        shp.fill.solid()
        shp.fill.fore_color.rgb = rgb(fill)
    else:
        shp.fill.background()
    if line:
        shp.line.color.rgb = rgb(line)
        shp.line.width = Pt(line_w)
    else:
        shp.line.fill.background()
    shp.shadow.inherit = False
    if radius is not None and shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        shp.adjustments[0] = radius
    return shp


def style_run(run, size, bold=False, color=None, italic=False, font=FONT):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = rgb(color or C["ink"])


def add_text(slide, l, t, w, h, text, size=16, bold=False, color=None, align=PP_ALIGN.LEFT,
             anchor=MSO_ANCHOR.TOP, italic=False, margin=0.05):
    tb = slide.shapes.add_textbox(Inches(l), Inches(t), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = Inches(margin)
    tf.margin_top = tf.margin_bottom = Inches(0.03)
    tf.vertical_anchor = anchor
    p = tf.paragraphs[0]
    p.alignment = align
    r = p.add_run()
    r.text = text
    style_run(r, size, bold, color, italic)
    return tb


def set_bullet(paragraph, color=None, indent_emu=285750):
    pPr = paragraph._p.get_or_add_pPr()
    pPr.set("marL", str(indent_emu))
    pPr.set("indent", str(-indent_emu))
    for tag in ("a:buClr", "a:buChar", "a:buNone"):
        for el in pPr.findall(qn(tag)):
            pPr.remove(el)
    buClr = etree.SubElement(pPr, qn("a:buClr"))
    srgb = etree.SubElement(buClr, qn("a:srgbClr"))
    srgb.set("val", color or C["amber"])
    bu = etree.SubElement(pPr, qn("a:buChar"))
    bu.set("char", "•")


def add_bullets(slide, l, t, w, h, bullets, max_pt=20):
    plain = [b.replace("||", " ") for b in bullets]
    size = fit_size(plain, w - 0.3, h, max_pt=max_pt)
    tb = slide.shapes.add_textbox(Inches(l), Inches(t), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = Inches(0.05)
    tf.margin_top = tf.margin_bottom = Inches(0.03)
    for i, b in enumerate(bullets):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(7)
        set_bullet(p)
        if "||" in b:
            lead, rest = b.split("||", 1)
            r1 = p.add_run()
            r1.text = lead
            style_run(r1, size, True, C["navy"])
            r2 = p.add_run()
            r2.text = rest
            style_run(r2, size, False, C["ink"])
        else:
            r = p.add_run()
            r.text = b
            style_run(r, size, False, C["ink"])
    return tb


